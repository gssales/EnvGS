#!/usr/bin/env python3
"""Export EnvGS into a Graphdeco-style test tree and benchmark its native model.

Run from the EnvGS repository root, in its installed CUDA/OptiX environment.
Reviewed against EnvGS 09993470ae76854e2dae1118374031c9b32891ac.
This adapter does not implement PSNR/SSIM/LPIPS or normal MAE.

Example (checkpoint path must be an actual file):
 python envgs_eval_adapter.py --config configs/exps/envgs/shiny_blender/envgs_ball.yaml \
   --checkpoint data/trained_model/envgs_ball/latest.pt --model-path /output/ball \
   --mode render --normal-space world
 python envgs_eval_adapter.py --config configs/exps/envgs/shiny_blender/envgs_ball.yaml \
   --checkpoint data/trained_model/envgs_ball/latest.pt --model-path /output/ball \
   --mode fps --repeats 100

Pass EasyVolCap overrides after --opts, e.g. --opts val_dataloader_cfg.dataset_cfg.ratio=1.0
Use the SAME scene configuration and relevant overrides as training. Resolution,
test split, crop, background, and normal coordinates must match other methods.
Only load trusted checkpoints: upstream loading permits pickled Python objects.

Outputs: test/envgs_<completed_iterations>/{renders,gt,normals,alpha}/*.png,
normal_vectors/*.npy, views.json, and model-path/{fps.txt,fps.json}.
normal_vectors contains HxWx3 float32 unit normals in the selected coordinate
system; normals PNGs encode (n+1)/2 without opacity multiplication. Invalid zero
vectors encode neutral gray; use GT validity/foreground masks for MAE.
views.json maps sequential filenames to EasyVolCap camera/frame/view indices.
No assumption is made about ordering of an external GT-normal directory.

FPS: warm up each view, then synchronize around a block of repeated native
model(batch) calls (or individually with --timing latency). Includes Python
dispatch, camera/ray preparation, base rasterization, reflection tracing and
normal/depth outputs. Excludes loading, transfer, exports and metrics. Static
evaluation BVH is built during warmup and reused, exactly as native evaluation.
Fresh batch containers prevent accidental reuse of rays generated by a prior
render. Reported FPS is total timed renders / total elapsed seconds.
Primitive count includes BOTH base and environment Gaussians.

Validation: syntax, CLI and container-copy checks only; PyTorch/CUDA execution
has not been tested in the authoring environment.
"""

import argparse
import json
import sys
import time
from pathlib import Path


def parse_args():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--config', required=True)
    p.add_argument('--checkpoint', required=True, help='Explicit .pt/.pth/.npz file')
    p.add_argument('--model-path', required=True, help='Output root used by your existing metrics scripts')
    p.add_argument('--mode', choices=['render', 'fps', 'both'], default='render')
    p.add_argument('--normal-space', choices=['world', 'camera-opencv', 'camera-opengl'])
    p.add_argument('--normal-source', choices=['gaussian', 'depth'], default='gaussian')
    p.add_argument('--method', default='envgs')
    p.add_argument('--iteration', type=int, help='Override completed iterations if ep_iter changed since training')
    p.add_argument('--repeats', type=int, default=100)
    p.add_argument('--warmup', type=int, default=10)
    p.add_argument('--timing', choices=['throughput', 'latency'], default='throughput')
    p.add_argument('--opts', nargs=argparse.REMAINDER, default=[])
    a = p.parse_args()
    if a.mode != 'fps' and a.normal_space is None:
        p.error('--normal-space is required for export; choose the convention of your GT normals')
    if a.repeats < 1 or a.warmup < 1:
        p.error('--repeats and --warmup must be positive')
    if not a.method or Path(a.method).name != a.method or a.method in ('.', '..'):
        p.error('--method must be a simple directory-name component')
    return a


def copy_containers(value):
    """Copy nested batch containers while sharing read-only tensor storage."""
    if isinstance(value, dict):
        return type(value)({k: copy_containers(v) for k, v in value.items()})
    if isinstance(value, list):
        return [copy_containers(v) for v in value]
    if isinstance(value, tuple):
        return tuple(copy_containers(v) for v in value)
    return value


def normal_coordinates(n, R, space):
    import torch.nn.functional as F
    n = F.normalize(n, dim=-1)
    if space != 'world':
        n = n @ R.mT  # world to camera for row-vector normals
    if space == 'camera-opengl':
        n = n * n.new_tensor([1, -1, -1])
    return F.normalize(n, dim=-1)


def save_png(path, values):
    import numpy as np
    from PIL import Image
    array = values.detach().float().cpu().numpy()
    if not np.isfinite(array).all():
        raise ValueError(f'Non-finite image values: {path}')
    # Same rounding convention as torchvision.utils.save_image.
    array = (array.clip(0, 1) * 255 + 0.5).astype(np.uint8)
    if array.shape[-1] == 1:
        array = array[..., 0]
    Image.fromarray(array).save(path)


def main():
    a = parse_args()
    checkpoint = Path(a.checkpoint).resolve()
    if not checkpoint.is_file() or checkpoint.suffix not in ('.pt', '.pth', '.npz'):
        raise ValueError('Provide an existing .pt, .pth or .npz checkpoint file')
    output_root = Path(a.model_path).resolve()
    # EasyVolCap parses argv on import. Keep our CLI separate from its parser.
    sys.argv = [sys.argv[0], '-t', 'test', '-c', a.config, *a.opts]
    import numpy as np
    import torch
    from easyvolcap.engine import cfg, MODELS, DATALOADERS
    from easyvolcap.scripts.main import preflight  # discovers/registers native modules
    from easyvolcap.utils.base_utils import dotdict
    from easyvolcap.utils.data_utils import add_iter, to_cuda
    from easyvolcap.utils.net_utils import load_pretrained
    from easyvolcap.utils.timer_utils import timer

    if not torch.cuda.is_available():
        raise RuntimeError('EnvGS rendering requires its CUDA/OptiX environment')
    preflight(**cfg)
    timer.disabled = True
    torch.cuda.set_device(0)  # CUDA_VISIBLE_DEVICES selects the physical GPU
    cfg.val_dataloader_cfg.max_iter = -1
    cfg.val_dataloader_cfg.batch_sampler_cfg.batch_size = 1
    cfg.val_dataloader_cfg.sampler_cfg.type = 'SequentialSampler'
    loader = DATALOADERS.build(cfg.val_dataloader_cfg)
    model = MODELS.build(cfg.model_cfg).to('cuda').eval()
    if hasattr(model, 'move_device'):
        model.move_device(torch.device('cuda:0'))
    state, loaded_path = load_pretrained(str(checkpoint), ext=checkpoint.suffix)
    if state is None:
        raise RuntimeError(f'Checkpoint could not be loaded: {checkpoint}')
    model.load_state_dict(state['model'], strict=True)
    epoch = int(state['epoch'])
    del state
    iteration = a.iteration if a.iteration is not None else (epoch + 1) * int(cfg.runner_cfg.ep_iter)
    if iteration <= 0:
        raise ValueError('Cannot infer completed iterations; supply --iteration')
    sampler = model.sampler
    if type(sampler).__name__ != 'EnvGSSampler':
        raise ValueError('This adapter expects EnvGSSampler')
    if sampler.use_base_tracing:
        raise ValueError('Experimental use_base_tracing=True is outside this adapter\'s verified source path')
    counts = {'base': int(sampler.pcd.get_xyz.shape[0]), 'environment': int(sampler.env.get_xyz.shape[0])}
    counts['total'] = counts['base'] + counts['environment']
    target = output_root / 'test' / f'{a.method}_{iteration}'
    exporting = a.mode in ('render', 'both')
    benchmarking = a.mode in ('fps', 'both')
    if exporting:
        if target.exists() and any(target.iterdir()):
            raise FileExistsError(f'Refusing to mix new images with existing output: {target}')
        for folder in ('renders', 'gt', 'normals', 'normal_vectors', 'alpha'):
            (target / folder).mkdir(parents=True, exist_ok=True)
    output_root.mkdir(parents=True, exist_ok=True)
    metadata = dict(checkpoint=str(loaded_path), config=str(Path(a.config).resolve()),
                    overrides=a.opts, checkpoint_epoch=epoch, iteration=iteration,
                    normal_space=a.normal_space, normal_source=a.normal_source,
                    primitive_counts=counts, views=[])
    timings = []

    with torch.inference_mode():
        for index, cpu_batch in enumerate(loader):
            cpu_batch = add_iter(cpu_batch, iteration - 1, int(cfg.runner_cfg.epochs) * int(cfg.runner_cfg.ep_iter))
            batch = to_cuda(cpu_batch)
            h, w = int(batch.meta.H[0]), int(batch.meta.W[0])
            if batch.K.shape[0] != 1:
                raise ValueError('Batch size must be one')
            if ('orig_h' in batch.meta and int(batch.meta.orig_h[0]) != h) or \
               ('orig_w' in batch.meta and int(batch.meta.orig_w[0]) != w):
                raise ValueError('Cropped input detected. Match full-image evaluation settings before exporting.')
            row = dict(filename=f'{index:05d}.png', height=h, width=w)
            for key in ('camera_index', 'frame_index', 'view_index', 'latent_index'):
                if key in batch.meta:
                    row[key] = int(batch.meta[key].reshape(-1)[0])
                elif key in batch:
                    row[key] = int(batch[key].reshape(-1)[0])
            metadata['views'].append(row)

            def render():
                fresh = copy_containers(batch)
                fresh.output = dotdict()
                return model(fresh)

            if exporting:
                out = render()
                rgb = out.rgb_map.reshape(h, w, 3)
                gt = batch.rgb
                # Match native visualizer's premultiplied GT background handling.
                if 'bg_color' in out and 'msk' in batch:
                    gt = gt + out.bg_color * (1 - batch.msk)
                key = 'norm_map' if a.normal_source == 'gaussian' else 'surf_norm_map'
                n = normal_coordinates(out[key], batch.R, a.normal_space).reshape(h, w, 3)
                if not torch.isfinite(n).all():
                    raise ValueError('Non-finite normal vectors')
                save_png(target / 'renders' / row['filename'], rgb)
                save_png(target / 'gt' / row['filename'], gt.reshape(h, w, 3))
                save_png(target / 'normals' / row['filename'], (n + 1) * 0.5)
                save_png(target / 'alpha' / row['filename'], out.acc_map.reshape(h, w, 1))
                np.save(target / 'normal_vectors' / f'{index:05d}.npy', n.cpu().numpy())
                del out, rgb, gt, n

            if benchmarking:
                # All input transfers and first-use BVH construction are outside timing.
                for _ in range(a.warmup):
                    render()
                torch.cuda.synchronize()
                start = time.perf_counter()
                for _ in range(a.repeats):
                    render()
                    if a.timing == 'latency':
                        torch.cuda.synchronize()
                torch.cuda.synchronize()
                elapsed = time.perf_counter() - start
                timings.append(dict(**row, seconds=elapsed, repeats=a.repeats, fps=a.repeats / elapsed))
            print(f'View {index}: {w}x{h}', flush=True)
    if not metadata['views']:
        raise RuntimeError('Validation split produced no views')
    if exporting:
        (target / 'views.json').write_text(json.dumps(metadata, indent=2) + '\n')
    if benchmarking:
        total_seconds = sum(x['seconds'] for x in timings)
        fps = len(timings) * a.repeats / total_seconds
        report = dict(metadata, fps=fps, count=counts['total'], timing=a.timing,
                      repeats=a.repeats, warmup=a.warmup, total_seconds=total_seconds,
                      gpu=torch.cuda.get_device_name(), torch_version=torch.__version__,
                      cuda_version=torch.version.cuda, scope='native model forward; warmed static BVH; no IO',
                      per_view=timings)
        (output_root / 'fps.json').write_text(json.dumps(report, indent=2) + '\n')
        (output_root / 'fps.txt').write_text(f'fps: {fps:.6f}\ncount: {counts["total"]}\n')
        print(f'FPS: {fps:.3f}; counts: {counts}', flush=True)
    print(f'Export directory: {target}' if exporting else f'FPS results: {output_root / "fps.json"}')


if __name__ == '__main__':
    main()
